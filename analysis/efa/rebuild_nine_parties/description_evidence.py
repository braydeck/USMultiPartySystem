#!/usr/bin/env python3
"""Evidence sheet for the nine party descriptions: what sets each party apart from its nearest neighbors, where it
is cohesive, deviant or mainstream, and where it is the most or least of any party.

Sources (CES 2024, weighted):
  viz/src/data/clusterProfiles.json  policy items and the app's extra items (guns, military, news, stock, turnout);
                                     the production payload the Parties tab shows
  analysis/efa/exploration/listwise_check/outputs/compare_typologies_k9/{demographics,factors}.csv
                                     demographic rows and the four factor centroids the signature page shows
                                     (same fit; policy values agree with clusterProfiles to 0.4 points on average)
Approval items (appr_*) are left out.

Rules (the signature page defaults, viz/src/lib/signature.ts):
  neighbors   the three nearest parties by Euclidean distance on the four factor centroids
  apart       the party differs from each of its three neighbors by >= 15 points (minGap)
  cohesive    share >= 70 or <= 30
  deviant     |share - everyone| >= 25
  mainstream  |share - everyone| <= 10, listed only where the nine parties span >= 40 points
  cohesive and mainstream  policy items both cohesive and mainstream where the parties span >= 40: a national consensus the party holds while others break from it
Writes analysis/efa/rebuild_nine_parties/description_evidence.md. Run from the repo root.
"""
import json
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[3]
CMP = ROOT / "analysis/efa/exploration/listwise_check/outputs/compare_typologies_k9"
OUT = Path(__file__).with_name("description_evidence.md")
ORDER = ["OAO", "PRG", "DSA", "LBR", "STY", "CUP", "CON", "NAT", "POP"]   # party_codes.LEFT_RIGHT
MIN_GAP, CONS, DEV, MAIN, MAIN_SPAN = 15, 70, 25, 10, 40
SKIP_DEMO = {"Median age", "Did not vote for president"}


def rows():
    profiles = {c["party"]: c["variables"] for c in json.loads((ROOT / "viz/src/data/clusterProfiles.json").read_text())}
    out = []
    for key, v in profiles["CON"].items():
        if key.startswith("appr_"):
            continue
        out.append({"kind": "policy", "domain": v["domain"], "label": v["question"], "us": v["overall"],
                    **{p: profiles[p][key]["pct"] for p in ORDER}})
    dem = pd.read_csv(CMP / "demographics.csv")
    # the file carries the old production parties under bare codes and the nine under "CODE (letter)"
    dem = dem[["section", "label", "Everyone"] + [c for c in dem.columns if " (" in c]]
    dem.columns = [c.split(" (")[0] for c in dem.columns]
    for _, r in dem.iterrows():
        if r["label"] in SKIP_DEMO:
            continue
        out.append({"kind": "demo", "domain": r["section"], "label": r["label"], "us": r["Everyone"],
                    **{p: r[p] for p in ORDER}})
    ages = dem.set_index("label").loc["Median age"]
    return out, {p: ages[p] for p in ORDER + ["Everyone"]}


def neighbors():
    f = pd.read_csv(CMP / "factors.csv", index_col=0)
    f = f.loc[[i for i in f.index if i.startswith("N: ")], [c for c in f.columns if " (" in c]]
    f.columns = [c.split(" (")[0] for c in f.columns]
    f.index = [i[3:] for i in f.index]
    X = f[ORDER].T
    d = pd.DataFrame(np.sqrt(((X.values[:, None] - X.values[None]) ** 2).sum(-1)), index=ORDER, columns=ORDER)
    return {p: list(d.loc[p].drop(p).sort_values().index[:3]) for p in ORDER}, d, X


def fmt(x):
    return f"{x:.0f}"


def main():
    R, ages, = rows()
    nb, dist, X = neighbors()
    md = ["# Party description evidence", "",
          "Generated by `description_evidence.py`; rules and sources in its docstring. Percentages are weighted shares "
          "of each party's members. **Apart** lists the items where the party differs from all three of its nearest "
          "neighbors by at least 15 points, sorted by the smallest of those three gaps.", ""]
    for p in ORDER:
        ns = nb[p]
        md += [f"## {p}", "",
               "Neighbors: " + ", ".join(f"{n} ({dist.loc[p, n]:.2f})" for n in ns) + ".  Factors: "
               + ", ".join(f"{k} {X.loc[p, k]:+.2f}" for k in X.columns) + f".  Median age {ages[p]:.0f} "
               f"(everyone {ages['Everyone']:.0f}).", ""]

        def rank_note(r):
            vals = sorted(ORDER, key=lambda q: r[q])
            if vals[-1] == p:
                return "highest of nine"
            if vals[0] == p:
                return "lowest of nine"
            grp = [p] + ns
            g = sorted(grp, key=lambda q: r[q])
            if g[-1] == p:
                return "highest of its neighbors"
            if g[0] == p:
                return "lowest of its neighbors"
            return ""

        apart = []
        for r in R:
            gaps = [r[p] - r[n] for n in ns]
            if all(abs(g) >= MIN_GAP for g in gaps):
                apart.append((min(abs(g) for g in gaps), r))
        apart.sort(key=lambda t: -t[0])
        md += [f"### Apart from {', '.join(ns)}", "", f"| item | {p} | " + " | ".join(ns) + " | everyone | note |",
               "|---|---|" + "---|" * len(ns) + "---|---|"]
        for gap, r in apart:
            md.append(f"| {r['label']} ({r['kind']}) | **{fmt(r[p])}** | " + " | ".join(fmt(r[n]) for n in ns)
                      + f" | {fmt(r['us'])} | {rank_note(r)} |")
        md.append("")

        for title, pick, key in [
            ("Cohesive (>= 70 or <= 30), policy", lambda r: r["kind"] == "policy" and (r[p] >= CONS or r[p] <= 100 - CONS),
             lambda r: -abs(r[p] - 50)),
            ("Deviant (>= 25 from everyone)", lambda r: abs(r[p] - r["us"]) >= DEV, lambda r: -abs(r[p] - r["us"])),
            (f"Mainstream (<= 10 from everyone, where parties span >= {MAIN_SPAN})",
             lambda r: abs(r[p] - r["us"]) <= MAIN and max(r[q] for q in ORDER) - min(r[q] for q in ORDER) >= MAIN_SPAN,
             lambda r: abs(r[p] - r["us"])),
            (f"Cohesive and mainstream, policy (>= 70 or <= 30, <= 10 from everyone, parties span >= {MAIN_SPAN})",
             lambda r: r["kind"] == "policy" and (r[p] >= CONS or r[p] <= 100 - CONS) and abs(r[p] - r["us"]) <= MAIN
             and max(r[q] for q in ORDER) - min(r[q] for q in ORDER) >= MAIN_SPAN,
             lambda r: -abs(r[p] - 50)),
            ("Most or least of any party", lambda r: rank_note(r).endswith("nine"), lambda r: -abs(r[p] - r["us"])),
        ]:
            sel = sorted([r for r in R if pick(r)], key=key)
            md += [f"### {title} ({len(sel)})", ""]
            md += [f"- {r['label']}: {fmt(r[p])} (everyone {fmt(r['us'])}; {r['kind']}"
                   + (f"; {rank_note(r)}" if rank_note(r) else "") + ")" for r in sel]
            md.append("")
    OUT.write_text("\n".join(md) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}  ({len(R)} rows per party)")
    for p in ORDER:
        print(p, "neighbors", nb[p])


if __name__ == "__main__":
    main()
